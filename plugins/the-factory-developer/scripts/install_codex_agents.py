"""Register TFD roles as native Codex subagents."""

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MANAGED = "# Generated by the TFD Codex adapter.\n"


def native_profiles():
    for path in sorted((ROOT / "agents").glob("*/agent.json")):
        agent = json.loads(path.read_text(encoding="utf-8"))
        sector = agent["sector"]
        if sector == "translator":
            skill = ROOT / "skills" / agent["skills"][0] / "SKILL.md"
            body = skill.read_text(encoding="utf-8").split("---", 2)[2].strip()
            instructions = (
                "Work only from the supplied message and routing context. Do not use tools or delegate. "
                "If there is no specialist destination, prepare the English intent for the main agent.\n\n" + body
            )
        else:
            instructions = (
                f"Act as the TFD {sector} sector. Follow the installed {agent['skills'][0]} skill and the assigned "
                "canonical task route. Return evidence to the coordinator in Brazilian Portuguese. "
                "Stay within the assigned scope, respect the current gate, and do not delegate further."
            )
        yield f"tfd_{sector}", agent["description"], instructions
    yield (
        "tfd_harness", "Read-only project status and current TFD gates for a coordinator.",
        "Inspect the project's canonical task, workflow, evidence and relevant Git status. Return a short report "
        "in Brazilian Portuguese with sources, blockers and next gate. Use read-only operations. Do not delegate. "
        "Treat missing evidence as pending and do not infer approval."
    )


def install(destination):
    destination.mkdir(parents=True, exist_ok=True)
    outputs = {}
    for name, description, instructions in native_profiles():
        path = destination / f"{name}.toml"
        if path.is_symlink() or (path.exists() and not path.read_text(encoding="utf-8").startswith(MANAGED)):
            raise ValueError(f"existing custom profile would be overwritten: {path}")
        fields = dict(name=name, description=description, developer_instructions=instructions)
        outputs[path] = MANAGED + "".join(f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
                                          for key, value in fields.items())
    for path, contents in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != contents:
            path.write_text(contents, encoding="utf-8", newline="\n")
    return len(outputs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--agents-dir", type=Path, required=True)
    args = parser.parse_args()
    try:
        print(f"Registered {install(args.agents_dir)} TFD subagents in {args.agents_dir}")
    except (OSError, ValueError) as exc:
        print(f"Agent registration failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
